        public static List<int> ExtractAffix(string text)
        {
            List<int> result = [];
            if (string.IsNullOrEmpty(text)) return result;

            foreach (var item in AffixMap)
            {
                if (text.Contains($"【{item.Key}】"))
                {
                    result.Add(item.Value.id);
                }
            }
            return result;
        }


        public static string FormatTuJian(string text)
        {
            if (string.IsNullOrEmpty(text)) return text;
            string result = text;

            foreach (var item in AffixMap)
            {
                result = result.Replace(
                    $"【{item.Key}】",
                    $"#c449491【<hy t={item.Key} l=2_101_{item.Value.category}_{item.Value.id} fhc=#e86524 ul=1>】#n"
                );
            }
            return result;
        }
